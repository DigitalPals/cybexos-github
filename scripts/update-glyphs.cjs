#!/usr/bin/env node
// Regenerate js/TablerGlyphs.js from Cybex OS's glyph table, keeping only the
// names this plugin's QML uses. The font (assets/tabler/outline.ttf) is Cybex
// OS's own Tabler 3.48.0 subset; copy it alongside when Cybex OS updates it.
//
//   node scripts/update-glyphs.cjs /path/to/CybexOS/desktop/quickshell/Common/TablerGlyphs.js
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const table = require(path.resolve(process.argv[2] || ""));
// Quoted words in QML that happen to be glyph names but are not icons.
const NOT_ICONS = new Set(["function", "key", "opacity", "update"]);

const files = ["Widget.qml", ...fs.readdirSync(path.join(root, "ui"))
    .filter(name => name.endsWith(".qml")).map(name => "ui/" + name)];
const names = new Set(["help-circle", "loader-2"]);
for (const file of files) {
    const source = fs.readFileSync(path.join(root, file), "utf8");
    for (const match of source.matchAll(/"([a-z][a-z0-9_-]*)"/g)) {
        if (!NOT_ICONS.has(match[1]) && table.has(match[1]))
            names.add(match[1]);
    }
}
const aliases = {};
const glyphs = {};
for (const name of [...names].sort()) {
    const canonical = table.canonical(name);
    if (name !== canonical)
        aliases[name] = canonical;
    glyphs[canonical] = table.GLYPHS[canonical];
}
const escape = text => text.replace(/[\u0080-￿]/g,
    ch => "\\u" + ch.charCodeAt(0).toString(16).padStart(4, "0"));
const out = `// Generated by scripts/update-glyphs.cjs from Cybex OS's table; do not edit.
// The Tabler 3.48.0 outline glyphs this plugin draws (MIT, assets/tabler/
// LICENSE). Semantic (Material-style) names map to Tabler names.

var ALIASES = {
${Object.keys(aliases).map(key => `    ${JSON.stringify(key)}: ${JSON.stringify(aliases[key])}`).join(",\n")}
};

var GLYPHS = {
${Object.keys(glyphs).sort().map(key => `    ${JSON.stringify(key)}: { outline: "${escape(glyphs[key].outline)}" }`).join(",\n")}
};

function canonical(name) {
    var key = String(name || "");
    return Object.prototype.hasOwnProperty.call(ALIASES, key) ? ALIASES[key] : key;
}

function has(name) {
    return Object.prototype.hasOwnProperty.call(GLYPHS, canonical(name));
}

function resolve(name) {
    if (!name) return { outline: "" };
    return has(name) ? GLYPHS[canonical(name)] : GLYPHS["help-circle"];
}

if (typeof module !== "undefined")
    module.exports = { ALIASES: ALIASES, GLYPHS: GLYPHS, canonical: canonical, has: has, resolve: resolve };
`;
fs.writeFileSync(path.join(root, "js/TablerGlyphs.js"), out);
console.log("glyphs:", Object.keys(glyphs).length);
